const HOUR = 60 * 60 * 1000;
const shift = (iso, hours) => new Date(new Date(iso).getTime() + hours * HOUR).toISOString();

/**
 * Riwayat status pesanan (terbaru di atas), disusun dari status saat ini.
 * TODO(API): ganti dengan riwayat status asli dari backend.
 */
export function orderHistory(item, now = new Date()) {
  const events = [
    {
      label: 'Pesanan dibuat · Menunggu respons',
      by: item.customer,
      at: item.createdAt,
      tone: 'warning',
    },
  ];
  const accepted = {
    label: 'Diterima penyedia',
    by: item.provider,
    at: shift(item.createdAt, 3),
    tone: 'info',
  };
  switch (item.status) {
    case 'menunggu':
      if (new Date(now) - new Date(item.createdAt) > 6 * HOUR)
        events.push({
          label: 'Pengingat dikirim ke penyedia',
          by: 'Sistem',
          at: shift(item.createdAt, 6),
          tone: 'warning',
        });
      break;
    case 'diterima':
      events.push(accepted);
      break;
    case 'berjalan':
      events.push(accepted, {
        label: 'Layanan dimulai',
        by: item.provider,
        at: item.start,
        tone: 'teal',
      });
      break;
    case 'selesai':
      events.push(
        accepted,
        { label: 'Layanan dimulai', by: item.provider, at: item.start, tone: 'teal' },
        {
          label: 'Pesanan selesai',
          by: item.customer,
          at: shift(item.start, item.hours),
          tone: 'success',
        },
      );
      break;
    case 'ditolak':
      events.push({
        label: 'Ditolak penyedia',
        by: item.provider,
        at: shift(item.createdAt, 5),
        tone: 'danger',
      });
      break;
    case 'dibatalkan':
      events.push(
        item.autoCancelled
          ? {
              label: 'Dibatalkan otomatis · tidak direspons 24 jam',
              by: 'Sistem',
              at: shift(item.createdAt, 24),
              tone: 'neutral',
            }
          : {
              label: 'Dibatalkan pengguna',
              by: item.customer,
              at: shift(item.createdAt, 20),
              tone: 'neutral',
            },
      );
      break;
    default:
  }
  return events.reverse();
}

